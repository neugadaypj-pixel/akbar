// ---------- Language state ----------
let currentLang = localStorage.getItem('market-lang') || 'en';

function t(key) {
  const dict = translations[currentLang] || translations.en;
  return dict[key] ?? translations.en[key] ?? key;
}

function applyStaticTranslations() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
}

function setLanguage(lang) {
  if (!translations[lang]) lang = 'en';
  currentLang = lang;
  localStorage.setItem('market-lang', lang);
  document.documentElement.lang = lang;
  document.querySelectorAll('.lang-btn').forEach((b) => {
    b.classList.toggle('active', b.dataset.lang === lang);
  });
  applyStaticTranslations();
  // Re-render current view
  if (typeof navigate === 'function') navigate(window.currentView || 'dashboard');
}

function getLanguage() {
  return currentLang;
}

// Expose
window.t = t;
window.setLanguage = setLanguage;
window.getLanguage = getLanguage;
window.applyStaticTranslations = applyStaticTranslations;

// Apply initial language + highlight active button on load
document.addEventListener('DOMContentLoaded', () => {
  document.documentElement.lang = currentLang;
  document.querySelectorAll('.lang-btn').forEach((b) => {
    b.classList.toggle('active', b.dataset.lang === currentLang);
  });
});
